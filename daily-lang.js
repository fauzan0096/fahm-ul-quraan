/* ===== Zubaan badalne par Aaj ki Ayat + Sunnat bhi badalte hain ===== */
(function () {
    // 8 zubaanein: nayi zubaan (mr/ar/fr/es) ka tarjuma yahan nahi, is liye English par gir jate hain
    function idx(v) { return { u: 0, ro: 1, hi: 2, en: 3, mr: 3, ar: 3, fr: 3, es: 3 }[v]; }
    function lang() {
        try { if (window.QSLang && QSLang.get) return QSLang.get() || 'u'; } catch (e) {}
        try { return localStorage.getItem('mlang') || 'u'; } catch (e) { return 'u'; }
    }
    function pick(entry, v) {
        var i = idx(v);
        if (i <= 0 || !entry || !entry.t) return null;
        return entry.t[i - 1] || null;
    }
    // app.js ke hawale kabhi "(آیت کا حصہ)" ke saath hote hain — us hisse ko hata kar dekho
    function key(ref) { return String(ref || '').replace(/\s*\([^)]*\)\s*$/, '').trim(); }
    function ayatOf(ref) {
        var a = ref ? (FQ_AYAT_L10N[ref] || FQ_AYAT_L10N[key(ref)]) : null;
        if (!a) return null;
        var i = idx(lang());
        return i <= 0 ? null : (a[i - 1] || null);
    }
    function sunnatEntry(s) {
        if (!s) return null;
        var e = (typeof s.__i === 'number') ? FQ_SUNNAT_L10N[s.__i] : null;
        if (!e) {
            for (var k = 0; k < FQ_SUNNAT_L10N.length; k++) {
                if (FQ_SUNNAT_L10N[k].ar === s.ar) { e = FQ_SUNNAT_L10N[k]; break; }
            }
        }
        return e || null;
    }
    function sunnatText(s) {
        var e = sunnatEntry(s);
        if (!e) return null;
        var t = pick(e, lang());
        if (!t) return null;
        return { ur: t, tip: pick({ t: e.tip }, lang()) || s.tip };
    }
    window.FQDual = { lang: lang, ayatOf: ayatOf, sunnatText: sunnatText };

    // App ka language button dabane par dono cards dobara likhe jayen
    function repaint() {
        try { if (window.FQDailyModal) window.FQDailyModal(); } catch (e) {}
        try { if (window.FQDailyAyat && window.FQDailyAyat.render) window.FQDailyAyat.render(); } catch (e) {}
    }
    try {
        if (window.QSLang && QSLang.onChange) QSLang.onChange(repaint);
    } catch (e) {}
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', repaint);
    else setTimeout(repaint, 0);
})();

