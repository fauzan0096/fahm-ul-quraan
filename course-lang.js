(function () {
  'use strict';
  var L = ['mr', 'ar', 'fr', 'es'];
  function apply() {
    var data = (typeof courseData !== 'undefined') ? courseData : window.courseData;
    if (!data || !data.length) return false;
    var T = window.FQ_COURSE_LANG || {}, n = 0;
    for (var d = 0; d < data.length; d++) {
      var ws = data[d].words || [];
      for (var i = 0; i < ws.length; i++) {
        var w = ws[i], e = T[w.a];
        if (!e) continue;
        for (var k = 0; k < L.length; k++) {
          var v = L[k], t = e[v];
          if (!t) continue;
          w['u_' + v] = t[0];
          if (t[1]) w['t_' + v] = t[1];
        }
        n++;
      }
    }
    window.FQ_COURSE_LANG_DONE = n;   // kitne lafz ka tarjuma lag gaya
    return n > 0;
  }
  if (!apply()) {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', apply);
    else window.addEventListener('load', apply);
  }
  window.FQCourseLangApply = apply;   // aage jode gaye hisse isse dobara lagate hain
})();


