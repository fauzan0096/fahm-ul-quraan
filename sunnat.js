function getTodaySunnat() {
    var n = new Date();
    var dayOfYear = Math.floor((Date.UTC(n.getFullYear(), n.getMonth(), n.getDate()) - Date.UTC(n.getFullYear(), 0, 0)) / 86400000);
    return SUNNATS[dayOfYear % SUNNATS.length];
}
